import XCTest
@testable import ClipboardManagerCore

final class TransientTypeDetectorTests: XCTestCase {
    func testIgnoresConcealedTypes() {
        XCTAssertTrue(TransientTypeDetector.shouldIgnore(
            types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
    }

    func testIgnoresTransientAndAutoGenerated() {
        XCTAssertTrue(TransientTypeDetector.shouldIgnore(types: ["org.nspasteboard.TransientType"]))
        XCTAssertTrue(TransientTypeDetector.shouldIgnore(types: ["org.nspasteboard.AutoGeneratedType"]))
        XCTAssertTrue(TransientTypeDetector.shouldIgnore(types: ["de.petermaurer.TransientPasteboardType"]))
    }

    func testKeepsPlainText() {
        XCTAssertFalse(TransientTypeDetector.shouldIgnore(types: ["public.utf8-plain-text"]))
    }
}
